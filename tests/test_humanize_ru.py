"""Регрессия: humanizer не должен ломать русскую грамматику (падежи, конструкции).

Запуск: python -m pytest tests  (или python tests/test_humanize_ru.py)
"""
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("humanize", ROOT / ".claude/skills/ig-human/humanize.py")
humanize = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(humanize)
LEX = humanize.load_lexicon()

# (вход, ожидаемый выход) — вводный штамп в начале предложения удаляется
CHANGED = [
    ("В современном мире маркетинг сложнее, чем кажется.", "Маркетинг сложнее, чем кажется."),
    ("Не секрет, что многие путают маркетинг и SMM.", "Многие путают маркетинг и SMM."),
    ("Ни для кого не секрет, что ИИ меняет работу.", "ИИ меняет работу."),
    ("Важно отметить, что рынок растёт.", "Рынок растёт."),
    ("На сегодняшний день у нас пять каналов.", "Сейчас у нас пять каналов."),
    ("Подводя итог, маркетинг — это система.", "Маркетинг — это система."),
    ("В заключение, хочу сказать спасибо.", "Хочу сказать спасибо."),
    ("Всем привет! Сегодня о маркетинге.", "Сегодня о маркетинге."),
    ("В наше время всё иначе.", "Всё иначе."),
    ("Давайте разберёмся. Почему так происходит?", "Почему так происходит?"),
]

# Внутри предложения или как часть конструкции — текст не трогается (только флаг)
UNCHANGED = [
    "Место бизнеса в современном мире изменилось.",
    "Для меня это не секрет, что бюджеты режут.",
    "Мне важно отметить, что рынок растёт.",
    "Давайте разберемся в этом вопросе подробнее.",
    "Давайте разберёмся, почему так происходит.",
    "Это мой план на сегодняшний день и на завтра.",
    "Задачи в данный момент распределены.",
    "Подписывайтесь, чтобы не пропустить новые посты.",
    "Ставь лайк, если согласен.",
    "Люди в наше время читают меньше.",
    "Маркетинг является частью стратегии в рамках компании.",   # канцелярит — только флаг
    "Маркетинг — это не только SMM.",                          # тире в русском не трогаем
    "Он сказал «это работает» и ушёл.",                        # ёлочки не трогаем
]


def clean(text):
    return humanize.humanize(text, LEX)[0].strip()


def test_changed():
    for src, expected in CHANGED:
        assert clean(src) == expected, (src, clean(src))


def test_unchanged():
    for src in UNCHANGED:
        assert clean(src) == src, (src, clean(src))


def test_multiline_keeps_lines():
    src = "В заключение, хочу сказать спасибо.\nВсем привет! Сегодня о маркетинге."
    assert clean(src) == "Хочу сказать спасибо.\nСегодня о маркетинге."


if __name__ == "__main__":
    test_changed()
    test_unchanged()
    test_multiline_keeps_lines()
    print("ok")
