    ("Он являлся частью команды.", "Он был частью команды."),
    ("Реклама будет являться основой продаж.", "Реклама будет основой продаж."),
    ("Подготовка данного проекта заняла месяц.", "Подготовка этого проекта заняла месяц."),
    ("В данной ситуации важно не спешить.", "В этой ситуации важно не спешить."),
    ("В связи с ростом цен мы пересмотрели бюджет.", "Из-за роста цен мы пересмотрели бюджет."),
